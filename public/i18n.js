  const LOCALES = { nl: "nl-BE", en: "en-AU" };
  const INDEX = { nl: 0, en: 1 };
  const KEY = "followup-lang";

  function initial() {
    try {
      const saved = localStorage.getItem(KEY);
      if (saved in INDEX) return saved;
    } catch (e) { /* privévenster */ }
    return (navigator.language || "nl").toLowerCase().startsWith("nl") ? "nl" : "en";
  }

  let lang = initial();
  const listeners = [];

  function t(key, vars) {
    const entry = TEXT[key];
    if (!entry) return key; // een ontbrekende sleutel valt op
    let s = entry[INDEX[lang]];
    if (vars) for (const [k, v] of Object.entries(vars)) s = s.split("{" + k + "}").join(String(v));
    return s;
  }
  const tv = (value) => (lang === "en" && Object.prototype.hasOwnProperty.call(VALUES_EN, value) ? VALUES_EN[value] : String(value ?? ""));

  // Vaste tekst in index.html: data-i18n (inhoud), data-i18n-ph (placeholder),
  // data-i18n-aria (aria-label) en data-i18n-title (title + aria-label als die er staat).
  function applyStatic(root = document) {
    root.querySelectorAll("[data-i18n]").forEach((el) => { el.textContent = t(el.dataset.i18n); });
    root.querySelectorAll("[data-i18n-aria]").forEach((el) => { el.setAttribute("aria-label", t(el.dataset.i18nAria)); });
    root.querySelectorAll("[data-i18n-ph]").forEach((el) => { el.placeholder = t(el.dataset.i18nPh); });
    root.querySelectorAll("[data-i18n-title]").forEach((el) => {
      el.title = t(el.dataset.i18nTitle);
      if (el.hasAttribute("aria-label")) el.setAttribute("aria-label", t(el.dataset.i18nTitle));
    });
  }

  function setLang(next) {
    if (!(next in INDEX) || next === lang) return;
    lang = next;
    try { localStorage.setItem(KEY, lang); } catch (e) { /* privévenster */ }
    document.documentElement.lang = lang;
    applyStatic();
    listeners.forEach((fn) => fn(lang));
  }

  return {
    t, tv, setLang, applyStatic,
    keys: () => Object.keys(TEXT),
    onChange: (fn) => listeners.push(fn),
    get lang() { return lang; },
    get locale() { return LOCALES[lang]; },
    get other() { return lang === "nl" ? "en" : "nl"; },
  };
